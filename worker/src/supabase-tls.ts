/**
 * How to connect securely to a database: Supabase hosts get TLS checked against Supabase's
 * certificate authority; anything else (a local test database) gets none.
 */
export function tlsFor(databaseUrl: string): { ca: string; servername: string; rejectUnauthorized: true } | false {
  const host = new URL(databaseUrl).hostname;
  return /\.supabase\.(co|com)$/.test(host) ? { ca: SUPABASE_ROOT_CA, servername: host, rejectUnauthorized: true } : false;
}
